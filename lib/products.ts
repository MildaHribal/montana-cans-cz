/** Sort modes offered in the catalogue toolbar. */
export type SortMode = 'doporucene' | 'nejlevnejsi' | 'nejdrazsi' | 'hodnoceni' | 'novinky';

export const SORTS: { id: SortMode; label: string }[] = [
  { id: 'doporucene', label: 'Doporučené' },
  { id: 'novinky', label: 'Novinky' },
  { id: 'nejlevnejsi', label: 'Nejlevnější' },
  { id: 'nejdrazsi', label: 'Nejdražší' },
  { id: 'hodnoceni', label: 'Nejlépe hodnocené' },
];

export function sortProducts(list: Product[], mode: SortMode): Product[] {
  const out = [...list];
  switch (mode) {
    case 'nejlevnejsi':
      return out.sort((a, b) => a.price - b.price);
    case 'nejdrazsi':
      return out.sort((a, b) => b.price - a.price);
    case 'hodnoceni':
      return out.sort((a, b) => b.rating - a.rating || b.reviews - a.reviews);
    case 'novinky':
      return out.sort(
        (a, b) => Number(b.badge === 'NOVÉ') - Number(a.badge === 'NOVÉ') || b.reviews - a.reviews,
      );
    default:
      /* "Doporučené" = in stock first, then by how much social proof it has. */
      return out.sort(
        (a, b) => Number(b.inStock) - Number(a.inStock) || b.reviews - a.reviews,
      );
  }
}

/** Czech price formatting — non-breaking space before the currency. */
export function formatPrice(czk: number): string {
  return `${czk.toLocaleString('cs-CZ')} Kč`;
}
