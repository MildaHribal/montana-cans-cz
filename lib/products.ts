/**
 * Catalogue for the mockup.
 *
 * Every product carries an `art` descriptor instead of an image path — the
 * whole catalogue is drawn as vector by `components/art`, so a shade can be
 * added by writing one line here rather than shooting a photo. Prices are
 * realistic Czech retail; codes line up with the MTN codes in `./colors`.
 */

export type ProductKind = 'spray' | 'marker' | 'cap' | 'apparel' | 'accessory';

export type CategorySlug = 'spreje' | 'fixy' | 'trysky' | 'obleceni' | 'doplnky';

export type Badge = 'NOVÉ' | 'BESTSELLER' | 'OMEZENÉ' | 'SLEVA' | 'PACK' | 'TIP';

/** Discriminated union consumed by `components/art/ProductArt`. */
export type ArtSpec =
  | { t: 'can'; series: CanSeries; volume: CanVolume }
  | { t: 'marker'; tip: MarkerTip; finish: 'acrylic' | 'ink' | 'chrome'; label?: string }
  | { t: 'cap'; style: 'fat' | 'skinny' | 'calligraphy' | 'universal' | 'super-fat' }
  | { t: 'apparel'; cut: 'tee' | 'hoodie' | 'cap' | 'crewneck'; print?: string }
  | { t: 'book'; size: 'A4' | 'A5' | 'square' }
  | { t: 'gloves' }
  | { t: 'stencil' }
  | { t: 'bag' }
  | { t: 'refill' };

export type Product = {
  id: string;
  name: string;
  /** Short line under the title in the card. */
  line: string;
  price: number;
  /** Struck-through original — presence drives the SLEVA treatment. */
  oldPrice?: number;
  kind: ProductKind;
  category: CategorySlug;
  /** Primary visual colour: tints the card glow and drives the vector render. */
  hex: string;
  colorCode?: string;
  colorName?: string;
  family?: ColorFamily;
  inStock: boolean;
  /** Drives the "poslední kusy" urgency pill. */
  stock?: number;
  badge?: Badge;
  rating: number;
  reviews: number;
  art: ArtSpec;
  /** MTN codes this item also comes in — rendered as swatch dots on the card. */
  variants?: string[];
  tags?: string[];
};

